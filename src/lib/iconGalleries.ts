export type IconifyData = { body: string; width?: number; height?: number }
export type IconGalleryEntry = { key: string; label: string; data: IconifyData }

function entry(key: string, label: string, data: { default: IconifyData } | IconifyData): IconGalleryEntry {
  const d = 'default' in data ? (data as { default: IconifyData }).default : data as IconifyData
  return { key, label, data: d }
}


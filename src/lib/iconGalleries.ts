const REGISTRY = new Map<string, IconifyData>()

function register(prefix: string, list: IconGalleryEntry[]) {
  list.forEach(({ key, data }) => REGISTRY.set(`${prefix}:${key}`, data))
}
register('ph', PH_ICONS)
register('bi', BI_ICONS)
register('tb', TB_ICONS)
register('mdi', MDI_ICONS)

export function getIconifyData(id: string): IconifyData | null {
  return REGISTRY.get(id) ?? null
}

export function searchGallery(prefix: string, list: IconGalleryEntry[], query: string): IconGalleryEntry[] {
  if (!query.trim()) return list
  const q = query.toLowerCase()
  return list.filter((e) => e.key.includes(q) || e.label.toLowerCase().includes(q))
}
